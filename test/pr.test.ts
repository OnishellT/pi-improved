test("scrub removes attribution lines only; product names in the work survive", () => {
  assert.equal(scrub("ok\nCo-Authored-By: Someone\nGenerated with Claude Code\nfine"), "ok\nfine");
  assert.equal(scrub("Generated by [Claude Code](https://claude.com)\nok"), "ok");
  assert.equal(scrub("Replace the OpenAI client with Gemini"), "Replace the OpenAI client with Gemini");
  assert.equal(prTitle({ ...task, ticket: undefined, title: "Replace OpenAI client with Gemini" }, []), "Replace OpenAI client with Gemini");
  assert.equal(branchName({ ...task, ticket: undefined, title: "OpenAI retry" }), "task/openai-retry");
  const body = buildBody({ task: { ...task, title: "Replace OpenAI client with Gemini", plan: undefined }, facts, verify: { ok: false, text: "FAIL copilot suite" } });
  assert.match(body, /Replace OpenAI client with Gemini/);
  assert.match(body, /FAIL copilot suite/);
  assert.equal(scrub("keep\nAssisted by Claude\nWritten with Claude Code\nend"), "keep\nend");
  assert.equal(prTitle({ ...task, ticket: undefined, title: "Generated with Claude Code" }, []), "Changes");
  assert.doesNotMatch(buildBody({ task, facts, verify: { ok: true, text: "ok\nCo-Authored-By: Someone" } }), /Co-Authored-By/);
});

